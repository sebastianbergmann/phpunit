namespace PHPUnit\Framework\Attributes;

use Attribute;

/**
 * Specifies the generator for a parameter of a property with a public static
 * method of another class than the test case class that returns it, for
 * instance #[ForAllExternal(MoneyGenerators::class, 'smallAmounts')].
 *
 * @immutable
 */
#[Attribute(Attribute::TARGET_PARAMETER)]
final readonly class ForAllExternal
{
    /**
     * @var class-string
     */
    private string $className;

    /**
     * @var non-empty-string
     */
    private string $methodName;

    /**
     * @param class-string     $className
     * @param non-empty-string $methodName
     */
    public function __construct(string $className, string $methodName)
    {
        $this->className  = $className;
        $this->methodName = $methodName;
    }

    /**
     * @return class-string
     */
    public function className(): string
    {
        return $this->className;
    }

    /**
     * @return non-empty-string
     */
    public function methodName(): string
    {
        return $this->methodName;
    }
}
